-- ============================================================
-- 考研刷题小程序 - 商城商品定价迁移（资料免费 → 积分兑换）
-- 用途: 在已有数据的环境上安全升级（不 DROP、不清数据，可重复执行）
-- 背景: 之前把 10 篇学习资料对应的商品价格设成了 0（免费领取），
--       导致「商城」没有实际兑换意义。本次改为按科目分档定价，
--       让商城回归「答题赚积分 → 积分换商品」的正循环。
-- 注意: 商品仍与 article 表一一对应（article_id 保留），
--       兑换成功后前端会跳文章详情；但文章本身在文章专栏里依然免费可读，
--       商城兑换的是「领取记录 / 权益凭证」。
-- 执行: mysql -uroot -p < mall_pricing_migration.sql
-- ============================================================

USE `just5min`;

-- ------------------------------------------------------------
-- 1. 资料商品定价（按科目分档）+ 库存收敛
--    政治/英语 50 积分、数学 60 积分、专业课 80 积分
--    price 恒 > 0，因此走 MallServiceImpl 的「先扣库存后扣积分」付费分支
-- ------------------------------------------------------------
UPDATE `mall_product` SET `price` = 50, `stock` = 999 WHERE `id` IN (1, 2, 5, 6, 9, 10);
UPDATE `mall_product` SET `price` = 60, `stock` = 999 WHERE `id` IN (3, 7);
UPDATE `mall_product` SET `price` = 80, `stock` = 999 WHERE `id` IN (4, 8);

-- 兜底：若还有 article_id 非空但价格仍为 0 的商品，按所属资料分类定价
-- （分类 id 语义：1政治 2英语 3数学 4专业课）
UPDATE `mall_product`
SET `price` = CASE `category_id`
        WHEN 1 THEN 50
        WHEN 2 THEN 50
        WHEN 3 THEN 60
        WHEN 4 THEN 80
        ELSE 50
    END,
    `stock` = 999
WHERE `article_id` IS NOT NULL AND (`price` IS NULL OR `price` <= 0);

-- ------------------------------------------------------------
-- 2. 分类名沿用「资料分类」语义（政治/英语/数学/专业课资料）
--    商城页直接展示为商品分类即可，这里不重复改名
-- ------------------------------------------------------------

-- ------------------------------------------------------------
-- 3. 自检输出
-- ------------------------------------------------------------
SELECT `id`, `category_id`, `name`, `price`, `stock`, `article_id`
FROM `mall_product`
ORDER BY `id`;
